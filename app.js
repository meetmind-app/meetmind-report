function renderReport(payload) {
  const meeting = payload.meeting;
  currentMeeting = meeting;
  const sourceLang = meeting.report_language || meeting.language || payload.language || 'en';
  currentLang = ['en', 'ru', 'es', 'pt'].includes(String(sourceLang).toLowerCase())
    ? String(sourceLang).toLowerCase()
    : 'en';
  setLabels();

  if (meeting.status === 'deleted' || meeting.deleted_at) {
    showDeletedState();
    return;
  }

  const report = normalizeReport(meeting.report || {});
  console.log(report);
  
  // The editable title is persisted inside report JSON by report-save.
  // Prefer the saved report title over the immutable/original meeting title.
  const title =
    report.meeting_title ||
    report.title ||
    meeting.meeting_title ||
    meeting.title ||
    t('meetingReport');
  
  document.title = `${title} — MeetMind AI`;
  $('meetingTitle').innerHTML = `
  <span class="editable-title" data-editable="true" data-field="meeting_title">${escapeHtml(title)}</span>
  `;

  renderMeta(meeting, report);
  renderStats(report);
  renderMetrics(report);
  
  if (!isEmptyValue(report.summary)) {
    $('summaryContent').innerHTML = renderTextBlock(report.summary);
    $('summaryContent').setAttribute('data-editable', 'true');
    $('summaryContent').setAttribute('data-field', 'summary');
    $('summarySection').classList.remove('hidden');
  }

renderDynamicCards(report);
renderTasksAndOwners(report);
renderTranscript(meeting.transcript);

  if (report.architecture?.sections?.length > 0) {
    $('architectureContent').innerHTML = renderArchitecture(report.architecture);
    $('architectureContent').setAttribute('data-editable', 'true');
    $('architectureContent').setAttribute('data-field', 'architecture');
}
  
  toggleSection(
    '#architectureSection',
    report.architecture?.sections?.length > 0
);
toggleSection(
    '#ownersSection',
    report.owners?.length > 0
);
toggleSection(
    '#transcriptSection',
    !!meeting.transcript?.trim()
);
const hasDetails =
    report.architecture?.sections?.length > 0 ||
    report.owners?.length > 0 ||
    !!meeting.transcript?.trim();
toggleSection('#detailsSection', hasDetails);

  if (meeting.branding_visible === false) $('brandingFooter').classList.add('hidden');

  $('loadingState').classList.add('hidden');
  $('reportPage').classList.remove('hidden');
  applyEditMode();
}

async function loadReportPayload() {
    const response = await fetch(
        `${REPORT_ENDPOINT}?token=${encodeURIComponent(currentToken)}`
    );

    if (!response.ok) {
        throw new Error(`HTTP ${response.status}`);
    }

    return await response.json();
}

async function loadReport() {
  const params = new URLSearchParams(window.location.search);
  currentToken = params.get('token');

  if (!currentToken) {
    showError(i18n.en.missingToken);
    return;
  }

  try {
    const payload = await loadReportPayload();

    if (!payload.success || !payload.meeting) {
      currentLang = payload.language || 'en';
      showError(t('notFound'));
      return;
    }

    renderReport(payload);
  } catch (error) {
    console.error(error);
    showError(i18n.en.notFound);
  }
}

