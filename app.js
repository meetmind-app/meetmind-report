function cleanupEmptyDynamicItems() {
    document.querySelectorAll('.report-item').forEach(item => {
        const editor = item.querySelector('.dynamic-item-editor');
        if (!editor) return;
        if (editor.innerText.trim() === '') {
            item.remove();
        }
    });
    document.querySelectorAll('.highlight-section').forEach(section => {
        if (!section.querySelector('.report-item')) {
            section.remove();
        }
    });

  const dynamicGrid = $('insightsDecisionsRisksGrid');
  if (dynamicGrid && !dynamicGrid.querySelector('.highlight-section')) {
    dynamicGrid.innerHTML = '';
    dynamicGrid.classList.add('hidden');
}

  document.querySelectorAll('.metric-card').forEach(card => {
    const label = card.querySelector('.metric-label');
    const value = card.querySelector('.metric-value');
    if (
        label &&
        value &&
        label.innerText.trim() === '' &&
        value.innerText.trim() === ''
    ) {
        card.remove();
    }
});
const metricsGrid = $('metricsContent');
if (metricsGrid && !metricsGrid.querySelector('.metric-card')) {
    $('metricsSection').classList.add('hidden');
}

  // Tasks: cards are smartphone-only; table is tablet/desktop.
  document.querySelectorAll('.task-table tbody tr').forEach(row => {
    const taskCell = row.querySelector('td:first-child');
    if (taskCell && !cleanText(taskCell.innerText)) row.remove();
  });
  document.querySelectorAll('.task-cards .task-card').forEach(card => {
    const title = card.querySelector('.task-title');
    if (title && !cleanText(title.innerText)) card.remove();
  });
  const activeTaskCount = window.matchMedia('(max-width: 767px)').matches
    ? document.querySelectorAll('.task-cards .task-card').length
    : document.querySelectorAll('.task-table tbody tr').length;
  toggleSection('#tasksSection', activeTaskCount > 0);

  // Owners: remove an owner card once both editable fields are empty.
  document.querySelectorAll('.owner-card').forEach(card => {
    const name = cleanText(card.querySelector('.owner-name')?.innerText);
    const role = cleanText(card.querySelector('.owner-role')?.innerText);
    if (!name && !role) card.remove();
  });
  toggleSection('#ownersSection', !!document.querySelector('.owner-card'));

  // Architecture: if the editable architecture body is emptied, hide the block.
  const architectureContent = $('architectureContent');
  const architectureVisible = !!architectureContent && !!cleanText(architectureContent.innerText);
  toggleSection('#architectureSection', architectureVisible);

  // Summary: no empty outer card.
  const summaryContent = $('summaryContent');
  toggleSection('#summarySection', !!summaryContent && !!cleanText(summaryContent.innerText));

  // Detailed report wrapper disappears when all detailed blocks are empty.
  const hasDetails =
    !$('#architectureSection')?.classList.contains('hidden') ||
    !$('#ownersSection')?.classList.contains('hidden') ||
    !$('#transcriptSection')?.classList.contains('hidden');
  toggleSection('#detailsSection', hasDetails);
}

function buildReportJson() {
    const baseReport = normalizeReport(currentMeeting?.report || {});

    function collectDynamicSection(sectionKey) {
        const section = document.querySelector(`.highlight-section.${sectionKey}`);
        if (!section) return [];

        return [...section.querySelectorAll('.report-item')]
            .map(item => {
                const editor = item.querySelector('.dynamic-item-editor');

                if (editor) {
                    const title = cleanText(editor.querySelector('strong')?.innerText);
                    const details = cleanText(editor.querySelector('.item-description')?.innerText);

                    if (!title && !details) return null;

                    return {
                        title,
                        details
                    };
                }

                const text = cleanText(item.innerText);
                return text ? { title: text, details: '' } : null;
            })
            .filter(Boolean);
    }

    function collectMetrics() {
        return [...document.querySelectorAll('.metric-card')]
            .map(card => ({
                label: cleanText(card.querySelector('.metric-label')?.innerText),
                value: cleanText(card.querySelector('.metric-value')?.innerText)
            }))
            .filter(metric => metric.label || metric.value);
    }

    function collectTasks() {
        // Smartphone UI edits cards; tablet/desktop edits the table.
        // Read from the representation the user actually edited.
        if (window.matchMedia('(max-width: 767px)').matches) {
            return [...document.querySelectorAll('.task-cards .task-card')]
                .map(card => ({
                    task: cleanText(card.querySelector('.task-title')?.innerText),
                    owner: cleanText(card.querySelector('.task-owner span')?.innerText),
                    due_date: cleanText(card.querySelector('.due-badge')?.innerText),
                    status: 'open'
                }))
                .filter(task => task.task);
        }

        return [...document.querySelectorAll('.task-table tbody tr')]
            .map(row => {
                const cells = row.querySelectorAll('td');

                return {
                    task: cleanText(cells[0]?.innerText),
                    owner: cleanText(cells[1]?.innerText),
                    due_date: cleanText(cells[2]?.innerText),
                    status: 'open'
                };
            })
            .filter(task => task.task);
    }

    function collectOwners() {
        return [...document.querySelectorAll('.owner-card')]
            .map(card => ({
                name: cleanText(card.querySelector('.owner-name')?.innerText),
                role: cleanText(card.querySelector('.owner-role')?.innerText)
            }))
            .filter(owner => owner.name || owner.role);
    }

    function collectArchitecture() {
        const sections = [...document.querySelectorAll('#architectureContent .architecture-section')]
            .map(section => {
                const title = cleanText(section.querySelector('.architecture-section-title')?.innerText);
                const layoutEl = [...section.querySelectorAll('div')]
                    .find(el => [...el.classList].some(cls => cls.startsWith('architecture-') && cls !== 'architecture-section'));

                const layoutClass = layoutEl
                    ? [...layoutEl.classList].find(cls => cls.startsWith('architecture-') && cls !== 'architecture-section')
                    : '';

                const layout = layoutClass ? layoutClass.replace('architecture-', '') : 'grid';

                const items = [...section.querySelectorAll('.architecture-item')]
                    .map(item => ({
                        title: cleanText(item.querySelector('h4')?.innerText),
                        description: cleanText(item.querySelector('p')?.innerText)
                    }))
                    .filter(item => item.title || item.description);

                if (!title && !items.length) return null;

                return {
                    title,
                    layout,
                    items
                };
            })
            .filter(Boolean);

        return { sections };
    }

    const title = cleanText(document.querySelector('.editable-title')?.innerText);
    const summary = cleanText($('summaryContent')?.innerText);
    const metrics = collectMetrics();

    return {
        ...baseReport,

        title,
        meeting_title: title,
        summary,
        executive_brief: summary,

        architecture: collectArchitecture(),

        key_metrics: metrics,
        metrics,

        insights: collectDynamicSection('insights'),
        decisions: collectDynamicSection('decisions'),
        risks: collectDynamicSection('risks'),

        tasks: collectTasks(),
        owners: collectOwners()
    };
}

async function saveReport() {
    const payload = {
        token: currentToken,
        report: buildReportJson()
    };

    console.log('Saving report...', payload);
    const response = await fetch(SAVE_ENDPOINT, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json'
        },
        body: JSON.stringify(payload)
    });
    if (!response.ok) {
        throw new Error(`Save failed: ${response.status}`);
    }

    const result = await response.json();
    const savedTitle = payload.report.meeting_title || payload.report.title || '';
    if (currentMeeting && savedTitle) {
        currentMeeting.title = savedTitle;
        document.title = `${savedTitle} — MeetMind AI`;
    }
    return result;
}

